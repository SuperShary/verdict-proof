import type { Extraction, Outcome, ReasonCode } from "@/lib/types";

/**
 * Demo invoices. One definition drives three things:
 *  1. scripts/generate-samples.ts renders each one to a PDF in public/samples/
 *  2. the unit tests run the ground-truth extraction through the rules engine
 *  3. tests/read-eval.live.ts (npm run eval:read) compares Gemini's reading against this ground truth
 * Order matters: history drives E1b (running PO balance) and E3 (duplicate of H1).
 */

export type Layout = "classic" | "modern" | "freight" | "scan" | "lab" | "quote";

export interface Sample {
  id: string;
  title: string;
  scenario: string; // what makes it interesting, one line
  file: string; // under /samples
  layout: Layout;
  senderEmail: string | null;
  expected: Outcome;
  expectedReasons: ReasonCode[]; // must be present on the decision (subset match)
  truth: Extraction;
  banner?: string; // extra line printed on the PDF (e.g. a "new bank details" notice)
}

